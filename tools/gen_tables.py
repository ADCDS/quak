#!/usr/bin/env python3
"""Generate src/quak/core/tables.py: HERO11 Black settings (with value names), statuses and
the operations GoPro documents as supported on HERO11 Black.

Sources (dev time only; Quak never imports them at runtime):
- Open GoPro docs site: the support tables are a JSON document embedded in one of the
  site's JS chunks as JSON.parse('...'). The chunk is parsed as text, never executed.
- GoPro's Python SDK (open_gopro) for status IDs, which the docs data doesn't carry.

    python3 -P tools/gen_tables.py            # fetch the docs data and regenerate
    python3 -P tools/gen_tables.py --chunk FILE.js
"""

import argparse
import json
import pprint
import re
import urllib.request
from pathlib import Path

BASE = "https://gopro.github.io/OpenGoPro"
CAMERA = "HERO11 Black"
OUT = Path(__file__).resolve().parents[1] / "src/quak/core/tables.py"
_JS_ESCAPES = {"n": "\n", "t": "\t", "r": "\r", "b": "\b", "f": "\f", "v": "\v", "0": "\0"}


def http_get(url: str) -> str:
    with urllib.request.urlopen(url, timeout=30) as r:  # noqa: S310 (fixed https host)
        return r.read().decode("utf-8")


def chunk_urls() -> list[str]:
    html = http_get(f"{BASE}/docs/ble/")
    runtime = re.search(r"runtime~main\.[0-9a-f]+\.js", html).group(0)
    js = http_get(f"{BASE}/assets/js/{runtime}")
    names, hashes = {}, {}
    for body in re.findall(r'\{((?:"?[\w~-]+"?:"[^"]+",?)+)\}', js):
        pairs = dict(re.findall(r'"?([\w~-]+)"?:"([^"]+)"', body))
        target = hashes if all(re.fullmatch(r"[0-9a-f]{8}", v) for v in pairs.values()) else names
        target.update(pairs)
    return [f"{BASE}/assets/js/{names.get(k, k)}.{h}.js" for k, h in hashes.items()]


def embedded_json(js: str) -> dict | None:
    start = js.find("JSON.parse('")
    if start < 0:
        return None
    start += len("JSON.parse('")
    end = js.index("')", start)

    def unescape(m: re.Match) -> str:
        g = m.group(1)
        return chr(int(g[1:], 16)) if g[0] in "ux" and len(g) > 1 else _JS_ESCAPES.get(g, g)

    return json.loads(re.sub(r"\\(u[0-9a-fA-F]{4}|x[0-9a-fA-F]{2}|.)", unescape, js[start:end], flags=re.S))


def find_tables(chunk: str | None) -> dict:
    sources = [Path(chunk).read_text(encoding="utf-8")] if chunk else (http_get(u) for u in chunk_urls())
    for js in sources:
        if '"OGP_PRESETS_GET"' not in js or "JSON.parse('" not in js:
            continue
        tables = [v for v in embedded_json(js).values() if isinstance(v, dict)]
        ops = [v for v in tables if any(k.startswith("OGP_") for k in v)]
        settings = [v for v in tables if isinstance(v.get("2"), dict) and "options" in v["2"]]
        if ops and settings:
            return {"operations": ops[0], "settings": settings[0]}
    raise SystemExit("support tables not found in the docs site")


def sdk_statuses() -> dict[int, str]:
    from open_gopro.models.constants.statuses import StatusId

    return {int(s): s.name.lower() for s in StatusId}


def sdk_preset_titles() -> dict[int, str]:
    from open_gopro.models.proto import preset_status_pb2

    special = {
        "SLOMO": "Slo-Mo",
        "HDR": "HDR",
        "POV": "POV",
        "FPV": "FPV",
        "4_3_VIDEO": "4:3 Video",
        "16_9_VIDEO": "16:9 Video",
        "16_9_SLOMO": "16:9 Slo-Mo",
        "TIME_WARP": "TimeWarp",
        "TIME_WARP_2": "TimeWarp",
        "PHOTO_2": "Photo",
        "ULTRA_SLO_MO": "Ultra Slo-Mo",
    }
    out = {}
    for v in preset_status_pb2.EnumPresetTitle.DESCRIPTOR.values:
        key = v.name.removeprefix("PRESET_TITLE_")
        out[v.number] = special.get(key, key.replace("_", " ").title())
    return out


def main() -> None:
    p = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    p.add_argument("--chunk", help="use a downloaded docs JS chunk instead of fetching")
    a = p.parse_args()
    t = find_tables(a.chunk)
    settings = {}
    for sid, s in sorted(t["settings"].items(), key=lambda kv: int(kv[0])):
        if CAMERA not in s.get("cameras", []):
            continue
        opts = {int(v): o["name"] for v, o in s.get("options", {}).items() if CAMERA in o.get("cameras", [])}
        settings[int(sid)] = {"name": s["name"], "format": s.get("format", "int8ub"), "options": opts}
    ops = {k: v["name"] for k, v in sorted(t["operations"].items()) if CAMERA in v.get("cameras", [])}
    statuses = sdk_statuses()
    titles = sdk_preset_titles()
    body = (
        '"""Generated by tools/gen_tables.py from GoPro\'s Open GoPro docs data and SDK. Do not edit."""\n\n'
        f"CAMERA = {CAMERA!r}\n\n"
        "# setting id -> {name, format, options: {value: name}} (HERO11 Black values only)\n"
        f"SETTINGS = {pprint.pformat(settings, width=110, sort_dicts=True)}\n\n"
        "# status id -> snake_case name\n"
        f"STATUSES = {pprint.pformat(statuses, width=110, sort_dicts=True)}\n\n"
        "# preset title id -> display name\n"
        f"PRESET_TITLES = {pprint.pformat(titles, width=110, sort_dicts=True)}\n\n"
        "# operations GoPro documents as supported on HERO11 Black\n"
        f"OPERATIONS = {pprint.pformat(ops, width=110, sort_dicts=True)}\n"
    )
    OUT.write_text(body, encoding="utf-8")
    print(f"wrote {OUT}: {len(settings)} settings, {len(statuses)} statuses, {len(ops)} operations")


if __name__ == "__main__":
    main()
